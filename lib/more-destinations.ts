const daily = (stay: [number, number, number], food: [number, number, number], local: [number, number, number]): Daily => ({
  budget: { stay: stay[0], food: food[0], local: local[0] },
  mid: { stay: stay[1], food: food[1], local: local[1] },
  comfort: { stay: stay[2], food: food[2], local: local[2] },
});

