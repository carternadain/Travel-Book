/** Room rate per night (2 sharing) → per-person daily numbers the planner uses. */
const wk = (room: [number, number, number], food: [number, number, number], local: [number, number, number]): Destination["daily"] => ({
  budget: { stay: Math.round(room[0] / 2), food: food[0], local: local[0] },
  mid: { stay: Math.round(room[1] / 2), food: food[1], local: local[1] },
  comfort: { stay: Math.round(room[2] / 2), food: food[2], local: local[2] },
});

function gem(
  id: string,
  name: string,
  wiki: string,
  lat: number,
  lng: number,
  days: number,
  tags: Interest[],
  blurb: string,
  extra: { tip?: string; tickets?: Ticket[]; photo?: string } = {},
): Place {
  return { id, name, wiki, lat, lng, kind: "gem", days, tags, blurb, ...extra };
}

const NPS = (park: string) => `https://www.nps.gov/${park}/planyourvisit/fees.htm`;
// Park passes are per vehicle; split between the two people in the car.
const carPass = (label: string, amount: number, park: string): Ticket => ({
  label: `${label} (½ of $${amount} car pass)`,
  amount: amount / 2,
  currency: "USD",
  source: NPS(park),
});

